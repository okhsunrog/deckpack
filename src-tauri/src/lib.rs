mod commands;
mod enclosures;

use specta_typescript::semantic;
use tauri_specta::{Builder, collect_commands};

/// Every command exposed to the webview; `tauri-specta` derives the
/// TypeScript bindings in `src/bindings.ts` from this list.
fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        // One TypeScript shape per Rust type: optional fields serialise as
        // `null` instead of being skipped, so both directions agree.
        .disable_serde_phases()
        // Millimetres are plain `number`s; NaN/Infinity never cross the IPC.
        .semantic_types(semantic::Configuration::default().enable_lossless_floats())
        .commands(collect_commands![
            commands::cell_library,
            commands::component_library,
            commands::enclosure_assets,
            commands::evaluate_workspace,
            commands::enumerate_plans,
            commands::holder_pieces,
            commands::export_holder_stl,
            enclosures::import_enclosure,
        ])
}

const BINDINGS_PATH: &str = "../src/bindings.ts";

fn export_bindings(builder: &Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default().header(
                "// @ts-nocheck\n// Generated by tauri-specta from src-tauri. Do not edit.",
            ),
            BINDINGS_PATH,
        )
        .expect("failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let specta = specta_builder();
    // Keep the bindings in sync with the Rust commands during development.
    #[cfg(debug_assertions)]
    export_bindings(&specta);

    let mut builder = tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_fs::init())
        .plugin(tauri_plugin_opener::init())
        .invoke_handler(specta.invoke_handler());

    // Debug-only bridge for the Tauri MCP server (@hypothesi/tauri-mcp-server):
    // lets an AI assistant drive the webview over a local WebSocket (port 9223+).
    #[cfg(debug_assertions)]
    {
        builder = builder.plugin(
            tauri_plugin_mcp_bridge::Builder::new()
                .bind_address("127.0.0.1")
                .build(),
        );
    }

    builder
        .setup(move |app| {
            specta.mount_events(app);
            enclosures::load_imported(app.handle());
            if cfg!(debug_assertions) {
                app.handle().plugin(
                    tauri_plugin_log::Builder::default()
                        .level(log::LevelFilter::Info)
                        .build(),
                )?;
            }
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Regenerates `src/bindings.ts`; CI fails if the committed file drifts.
    #[test]
    fn typescript_bindings_are_current() {
        export_bindings(&specta_builder());
    }
}
